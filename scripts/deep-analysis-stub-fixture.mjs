// Reads a hand-coded project directory and writes the fixture the deep-analysis
// stub replays. Run it whenever the coded project changes:
//
//   node scripts/deep-analysis-stub-fixture.mjs ~/nabu-notes-coded/<project-id>
//
// Companion, settings and codebook files are skipped: the stub only produces
// annotations for the documents a coding pass would target.

import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import { join, dirname, relative } from "node:path"
import { fileURLToPath } from "node:url"

const OUT = join(
  dirname(fileURLToPath(import.meta.url)),
  "../app/lib/agent/tools/apply-deep-analysis/stub-fixture.ts"
)

const SKIP = /(\.hidden\.md$|\.embeddings\.|^settings|^preferences|^welcome)/

const projectDir = process.argv[2]
if (!projectDir) {
  console.error("usage: node scripts/deep-analysis-stub-fixture.mjs <coded-project-dir>")
  process.exit(1)
}

const annotationsBlock = (raw) => {
  const match = raw.match(/```json-annotations\n([\s\S]*?)\n```/)
  return match ? JSON.parse(match[1]).annotations : []
}

const rows = []
for (const file of readdirSync(projectDir).sort()) {
  if (!file.endsWith(".md") || SKIP.test(file)) continue
  for (const a of annotationsBlock(readFileSync(join(projectDir, file), "utf8"))) {
    if (!a.code) continue
    rows.push({ file, code: a.code, text: a.text, reason: a.reason })
  }
}

const header = `// Generated by scripts/deep-analysis-stub-fixture.mjs — do not edit by hand.
// Source: a hand-coded project directory. ${rows.length} annotations.

export interface StubAnnotation {
  file: string
  code: string
  text: string
  reason: string
}

export const STUB_ANNOTATIONS: readonly StubAnnotation[] = `

writeFileSync(OUT, header + JSON.stringify(rows, null, 2) + "\n")
console.log(`${rows.length} annotations from ${projectDir} -> ${relative(process.cwd(), OUT)}`)
